#  FOR percorrendo listas
cores = ["Vermelho", "Verde", "Azul"]
for cor in cores:
    print(f"Pintando a tela com a cor: {cor}")

# FOR numérico com range()
# range(início, parada, passo) - A não é incluída.
print("Contagem regressiva:")
for i in range(5, 0, -1):
    print(i) # Vai imprimir 5, 4, 3, 2, 1

print("Contagem de 0 a 10:")
for i in range(0, 11):
    print(i)

